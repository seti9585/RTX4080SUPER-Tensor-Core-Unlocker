"""Prepare exact AD102 assets locally; never execute firmware or alter the EFI."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
import tarfile
import tempfile
import urllib.request
import uuid
from volume_identity import validate_target, inspect_target

HERE = Path(__file__).resolve().parent
SPEC = json.loads((HERE / 'manifest.json').read_text(encoding='utf-8-sig'))

def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()

def verify(folder):
    result = {}
    for name, spec in SPEC['assets'].items():
        path = folder / name
        if path.is_symlink() or not path.is_file():
            raise ValueError('Missing or unsafe asset: ' + name)
        if path.stat().st_size != spec['size'] or digest(path) != spec['sha256']:
            raise ValueError('Asset size/hash mismatch: ' + name)
        result[name] = spec
    return result

def fetch(entry, cache, offline):
    cache.mkdir(parents=True, exist_ok=True)
    path = cache / entry['filename']
    if path.exists():
        if path.is_symlink() or digest(path) != entry['sha256']:
            raise ValueError('Invalid cached archive: ' + path.name)
        return path
    if offline:
        raise FileNotFoundError('Missing archive: ' + path.name)
    print('Downloading pinned archive: ' + entry['filename'], flush=True)
    url = entry['url']
    if not url.startswith('https://'):
        raise ValueError('HTTPS required')
    partial = cache / ('.download-' + uuid.uuid4().hex)
    try:
        request = urllib.request.Request(url, headers={'User-Agent': 'AD103-local-assets/1.0'})
        with urllib.request.urlopen(request, timeout=60) as response, partial.open('xb') as stream:
            if not response.url.startswith('https://'):
                raise ValueError('Non-HTTPS redirect refused')
            total = 0
            while True:
                block = response.read(1024 * 1024)
                if not block:
                    break
                total += len(block)
                if total > 1024 * 1024 * 1024:
                    raise ValueError('Archive exceeds download limit')
                stream.write(block)
            stream.flush()
            os.fsync(stream.fileno())
        if digest(partial) != entry['sha256']:
            raise ValueError('Downloaded archive hash mismatch')
        os.replace(partial, path)
        return path
    finally:
        partial.unlink(missing_ok=True)

def prepare(source, package, work):
    import zstandard
    import extract_boot_assets
    import ad102_payload
    work.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='assets-', dir=work) as temp:
        root = Path(temp)
        derived = root / 'derived'
        derived.mkdir()
        report = extract_boot_assets.extract_arch(source, derived, 'AD102')
        stage = root / 'verified'
        stage.mkdir()
        for name in ('booter_load_ad102.bin', 'gsp_boot_ad102.bin', 'gsp_boot_desc_ad102.bin'):
            shutil.copyfile(derived / name, stage / name)
        member_name = SPEC['package']['firmware'][0]['path']
        found = False
        with package.open('rb') as raw, zstandard.ZstdDecompressor().stream_reader(raw) as reader:
            with tarfile.open(fileobj=reader, mode='r|') as archive:
                for member in archive:
                    if member.name != member_name:
                        continue
                    if found or not member.isfile() or member.size != SPEC['assets']['gsp_ga10x.bin']['size']:
                        raise ValueError('Invalid or duplicate firmware member')
                    found = True
                    item = archive.extractfile(member)
                    if item is None:
                        raise ValueError('Unreadable firmware member')
                    with item, (stage / 'gsp_ga10x.bin').open('xb') as output:
                        shutil.copyfileobj(item, output, 1024 * 1024)
        if not found:
            raise ValueError('Required firmware member missing')
        # Generate the exact existing payload; never download an upstream payload binary.
        (stage / 'v67-ad102-610.43.03-four-plm.bin').write_bytes(ad102_payload.payload())
        verify(stage)
        final = work / ('verified-' + uuid.uuid4().hex)
        shutil.copytree(stage, final)
        (final / 'verification.json').write_text(json.dumps({'assets': verify(final), 'extraction': report,
            'v67': 'locally generated by unchanged AD102 payload()'}, indent=2) + '\n', encoding='utf-8')
        return final

def deploy(source, target, work, confirmed_guid):
    validate_target(target, confirmed_guid)
    verify(source)
    if not target.is_dir():
        raise FileNotFoundError('Target drive does not exist')
    if not (target / 'EFI' / 'BOOT' / 'BOOTX64.EFI').is_file():
        raise ValueError('Target must contain the intended EFI boot application')
    parent = target / 'RTX4080-EXPERIMENT'
    assets = parent / 'ASSETS'
    if parent.is_symlink() or parent.is_junction() or assets.is_symlink() or assets.is_junction():
        raise ValueError('Redirected runtime directories refused')
    existing = set()
    for name, spec in SPEC['assets'].items():
        path = assets / name
        if path.exists():
            if path.is_symlink() or not path.is_file() or path.stat().st_size != spec['size'] or digest(path) != spec['sha256']:
                raise ValueError('Unknown existing asset refused: ' + name)
            existing.add(name)
    pending = set(SPEC['assets']) - existing
    if not pending:
        print('SKIP: all five target assets already match; no backup or write needed')
        return None
    backup = work / ('backup-' + uuid.uuid4().hex)
    backup.mkdir()
    for name in existing:
        shutil.copyfile(assets / name, backup / name)
        if digest(backup / name) != SPEC['assets'][name]['sha256']:
            raise ValueError('Backup verification failed: ' + name)
    (backup / 'existing.json').write_text(json.dumps(sorted(existing)), encoding='utf-8')
    assets.mkdir(parents=True, exist_ok=True)
    staged = {}
    replaced = []
    cleanup_allowed = True
    try:
        for name, spec in SPEC['assets'].items():
            if name not in pending:
                continue
            path = assets / ('.' + name + '-' + uuid.uuid4().hex + '.tmp')
            staged[name] = path
            shutil.copyfile(source / name, path)
            if path.stat().st_size != spec['size'] or digest(path) != spec['sha256']:
                raise ValueError('Staged copy mismatch: ' + name)
        validate_target(target, confirmed_guid)
        for name, path in staged.items():
            validate_target(target, confirmed_guid)
            if (assets / name).exists():
                raise ValueError('Destination appeared during deployment: ' + name)
            os.replace(path, assets / name)
            replaced.append(name)
        verify(assets)
    except Exception:
        try:
            validate_target(target, confirmed_guid)
        except Exception as identity_error:
            cleanup_allowed = False
            raise RuntimeError('Target identity unavailable; stopped without further drive writes; review staging files on the original volume') from identity_error
        for name in replaced:
            if name in existing:
                shutil.copyfile(backup / name, assets / name)
            else:
                (assets / name).unlink(missing_ok=True)
        for name in existing:
            if digest(assets / name) != SPEC['assets'][name]['sha256']:
                raise ValueError('Rollback verification failed: ' + name)
        raise
    finally:
        if cleanup_allowed:
            for path in staged.values():
                path.unlink(missing_ok=True)
    return backup

def main():
    if sys.version_info < (3, 12):
        print('FAILED: Python 3.12 or newer is required', file=sys.stderr)
        return 1
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=HERE.parent / 'local' / 'cache')
    parser.add_argument('--work', type=Path, default=HERE.parent / 'local' / 'work')
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--accept-terms', action='store_true', help='Confirm review of upstream terms; not a legal guarantee')
    parser.add_argument('--target', type=Path, help='Explicitly confirmed boot drive root')
    parser.add_argument('--confirm-volume-guid')
    parser.add_argument('--inspect-target', type=Path)
    parser.add_argument('--verify-only', type=Path)
    args = parser.parse_args()
    try:
        if sum(bool(value) for value in (args.inspect_target, args.target, args.verify_only)) > 1:
            raise ValueError('Use only one target operation')
        if args.inspect_target:
            print(json.dumps(inspect_target(args.inspect_target), indent=2))
            return 0
        if args.target:
            print(json.dumps(inspect_target(args.target), indent=2))
        if args.verify_only:
            verify(args.verify_only)
            print('PASS: all five sizes and SHA-256 values match')
            return 0
        if args.target:
            validate_target(args.target, args.confirm_volume_guid)
            assets = args.target / 'RTX4080-EXPERIMENT' / 'ASSETS'
            parent = assets.parent
            if parent.is_symlink() or parent.is_junction() or assets.is_symlink() or assets.is_junction():
                raise ValueError('Redirected runtime directories refused')
            if not (args.target / 'EFI' / 'BOOT' / 'BOOTX64.EFI').is_file():
                raise ValueError('Target boot EFI missing')
            if all((assets / name).is_file() for name in SPEC['assets']):
                verify(assets)
                print('SKIP: target verified; no download, generation, backup or write needed')
                return 0
        if not args.offline and not args.accept_terms:
            raise ValueError('Review README and upstream terms; use --accept-terms or supply verified archives with --offline')
        source = fetch(SPEC['source'], args.cache, args.offline)
        package = fetch(SPEC['package'], args.cache, args.offline)
        result = prepare(source, package, args.work)
        print('PASS: exact five assets prepared: ' + str(result), flush=True)
        if args.target:
            backup = deploy(result, args.target, args.work, args.confirm_volume_guid)
            if backup is not None:
                print('PASS: missing assets deployed and read back; backup: ' + str(backup))
        return 0
    except Exception as error:
        print('FAILED: ' + str(error), file=sys.stderr)
        return 1

if __name__ == '__main__':
    raise SystemExit(main())
